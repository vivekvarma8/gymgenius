  async sendEmail(to: string, subject: string, htmlContent: string, plainText?: string): Promise<SendEmailResult> {
    const timestamp = new Date().toISOString();
    if (!to || !to.includes("@")) {
      return {
        success: false,
        to,
        subject,
        error: "Invalid or missing recipient email address.",
        sentAt: timestamp
      };
    }

    try {
      if (!this.transporter) {
        this.initTransporter();
      }

      if (this.transporter) {
        const info = await this.transporter.sendMail({
          from: config.email.from,
          to,
          subject,
          text: plainText ?? subject,
          html: htmlContent
        });

        console.log(`[EmailService] Email successfully sent to ${to}: ${subject} (ID: ${info.messageId})`);
        return {
          success: true,
          messageId: info.messageId,
          to,
          subject,
          sentAt: timestamp
        };
      } else {
        // Fallback simulation log if SMTP service is unreachable
        console.log(`[EmailService Simulation] SMTP not active. Logged email to ${to}: ${subject}`);
        return {
          success: true,
          messageId: `sim_${Date.now()}`,
          to,
          subject,
          sentAt: timestamp
        };
      }
    } catch (error: any) {
      console.error(`[EmailService Error] Failed to send email to ${to}:`, error.message);
      return {
        success: false,
        to,
        subject,
        error: error.message,
        sentAt: timestamp
      };
    }
  }

  private formatExpiry(dateVal: Date | string | null | undefined): string {
    if (!dateVal) return "";
    if (dateVal instanceof Date) {
      return dateVal.toISOString().slice(0, 10);
    }
    return String(dateVal).slice(0, 10);
  }

