  // 7. Custom Direct Notice / Message to a specific member
  async sendCustomEmail(to: string, memberName: string, subject: string, messageBody: string): Promise<SendEmailResult> {
    const formattedBody = messageBody
      .replace(/\n\n/g, "</p><p>")
      .replace(/\n/g, "<br/>")
      .replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>");

    const html = this.buildEmailTemplate(
      subject,
      `Hello ${memberName || "Member"},`,
      `<div style="font-size: 14px; line-height: 1.65; color: #f4f4f5;">${formattedBody}</div>`
    );

    const result = await this.sendEmail(to, subject, html, messageBody);
    this.logResult(to, subject, "custom_notice", memberName, result.success);
    return result;
  }

  // 8. Bulk Announcement to a filtered list of members
  async sendBulkAnnouncement(
    members: Member[],
    subject: string,
    messageBody: string
  ): Promise<{
    total: number;
    sent: number;
    failed: number;
    recipients: Array<{ name: string; email: string; success: boolean }>;
  }> {
    const results: Array<{ name: string; email: string; success: boolean }> = [];
    let sent = 0;
    let failed = 0;

    for (const m of members) {
      if (!m.email) {
        failed++;
        continue;
      }
      const name = `${m.firstName || ""} ${m.lastName ?? ""}`.trim() || "Member";
      const res = await this.sendCustomEmail(m.email, name, subject, messageBody);
      if (res.success) {
        sent++;
        results.push({ name, email: m.email, success: true });
      } else {
        failed++;
        results.push({ name, email: m.email, success: false });
      }
    }

    return {
      total: members.length,
      sent,
      failed,
      recipients: results
    };
  }

  private logResult(to: string, subject: string, type: string, memberName: string, success: boolean): void {
    this.recentLogs.unshift({
      id: `mail_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
      to,
      subject,
      type,
      memberName,
      success,
      timestamp: new Date().toISOString()
    });
    if (this.recentLogs.length > 100) {
      this.recentLogs.pop();
    }
  }

  getRecentLogs(): EmailLogEntry[] {
    return this.recentLogs;
  }
